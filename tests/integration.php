<?php
// Execute ONLY in a fresh disposable WordPress installation: wp eval-file ...
require_once dirname(__DIR__) . '/app/Auth.php';
use SwimlogStandalone\Auth;
if (getenv('SWIMLOG_SYNTHETIC_TEST') !== '1') throw new RuntimeException('Disposable test flag required.');
$GLOBALS['count'] = 0;
function check($value) { global $count; ++$count; if (!$value) throw new RuntimeException('Assertion failed: ' . $count); }
function rejects($callback) { try { $callback(); } catch (RuntimeException $e) { check(true); return; } check(false); }
$owner = wp_create_user('synthetic_swimmer', wp_generate_password(32), 'swimmer@example.test');
$other = wp_create_user('synthetic_other', wp_generate_password(32), 'other@example.test');
if (is_wp_error($owner) || is_wp_error($other)) throw new RuntimeException('Fresh database required.');
get_user_by('id', $owner)->add_cap('swimlog_view_own_results');
wp_set_current_user($owner);
$_SERVER['REQUEST_METHOD'] = 'GET';
$expires = time() + 3600;
$token = WP_Session_Tokens::get_instance($owner)->create($expires);
$cookie = wp_generate_auth_cookie($owner, $expires, 'logged_in', $token);
$_COOKIE[LOGGED_IN_COOKIE] = $cookie;
check(Auth::cookieUser() === $owner);
check(Auth::requireCapability($owner));
check(!Auth::requireCapability($other));
$verifier = Auth::random(); $challenge = hash('sha256', $verifier);
$code = Auth::issue($challenge, $cookie);
check(Auth::valid($code));
$stored = get_option('swimlog_sso_' . hash('sha256', $code));
check(strpos($stored, $cookie) === false && strpos($stored, $token) === false);
rejects(function() use ($code) { Auth::redeem($code, Auth::random()); });
check(Auth::redeem($code, $verifier) === $cookie);
rejects(function() use ($code, $verifier) { Auth::redeem($code, $verifier); });
wp_cache_set('swimlog_sso_' . hash('sha256', $code), $stored, 'options');
rejects(function() use ($code, $verifier) { Auth::redeem($code, $verifier); });
wp_cache_delete('swimlog_sso_' . hash('sha256', $code), 'options');
$seal = new ReflectionMethod(Auth::class, 'seal'); if (PHP_VERSION_ID < 80100) $seal->setAccessible(true);
$expiredCode = Auth::random(); $expiredKey = 'swimlog_sso_' . hash('sha256', $expiredCode);
add_option($expiredKey, $seal->invoke(null, array('challenge' => $challenge, 'cookie' => $cookie, 'owner' => $owner, 'expires' => time()-1)), '', false);
rejects(function() use ($expiredCode, $verifier) { Auth::redeem($expiredCode, $verifier); });
Auth::cleanup($expiredKey);
check(false === get_option($expiredKey));
check((int)wp_parse_auth_cookie($cookie, 'logged_in')['expiration'] === $expires);
rejects(function() use ($cookie) { Auth::issue('invalid', $cookie); });
rejects(function() use ($cookie, $challenge, $other) { wp_set_current_user($other); Auth::issue($challenge, $cookie); });
wp_set_current_user($owner);
$code = Auth::issue($challenge, $cookie);
get_user_by('id', $owner)->remove_cap('swimlog_view_own_results');
rejects(function() use ($code, $verifier) { Auth::redeem($code, $verifier); });
get_user_by('id', $owner)->add_cap('swimlog_view_own_results');
Auth::cleanup('swimlog_sso_' . hash('sha256', $code));
$code = Auth::issue($challenge, $cookie);
WP_Session_Tokens::get_instance($owner)->destroy($token);
rejects(function() use ($code, $verifier) { Auth::redeem($code, $verifier); });
check(Auth::cookieUser($cookie) === 0);
Auth::cleanup('swimlog_sso_' . hash('sha256', $code));
$expired = wp_generate_auth_cookie($owner, time() - 1, 'logged_in');
$_SERVER['REQUEST_METHOD'] = 'POST';
check(Auth::cookieUser($expired) === 0);
foreach (array('http://example.test', 'https://evil.test/path', 'https://user@evil.test', 'https://evil.test?next=x') as $origin) rejects(function() use ($origin) { Auth::origin($origin); });
check(Auth::origin('https://swimlog.example.test/') === 'https://swimlog.example.test');
check(!Auth::valid(array('x')));
check(!Auth::valid(str_repeat('a', 63)));
echo "Authentication integration passed: " . $GLOBALS['count'] . " assertions.\n";
